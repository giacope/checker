class FakeOSV:
    """OSV's querybatch and vulns endpoints over a fixed advisory set; counts requests."""

    def __init__(self, records: list[dict], fail_first: int = 0, status: int = 503):
        self.records = {r["id"]: r for r in records}
        self.calls: list[tuple[str, str, int]] = []
        self.fail_first, self.status = fail_first, status

    def affects(self, rec, q):
        for a in rec["affected"]:
            if a["package"]["name"].lower() == q["package"]["name"].lower() and a["package"]["ecosystem"] == q["package"]["ecosystem"]:
                fixed = [e["fixed"] for r in a["ranges"] for e in r["events"] if "fixed" in e]
                if not fixed or any(deps.is_newer(q["package"]["ecosystem"], f, q["version"]) for f in fixed):
                    return True
        return False

    def __call__(self, request: httpx.Request) -> httpx.Response:
        if self.fail_first:
            self.fail_first -= 1
            self.calls.append((request.method, request.url.path, 0))
            return httpx.Response(self.status)
        if request.url.path == "/v1/querybatch":
            queries = json.loads(request.content)["queries"]
            self.calls.append(("POST", "/v1/querybatch", len(queries)))
            results = []
            for q in queries:
                hits = [{"id": r["id"], "modified": r["modified"]} for r in self.records.values() if self.affects(r, q)]
                results.append({"vulns": hits} if hits else {})
            return httpx.Response(200, json={"results": results})
        vid = request.url.path.rsplit("/", 1)[1]
        self.calls.append(("GET", request.url.path, 1))
        return httpx.Response(200, json=self.records[vid]) if vid in self.records else httpx.Response(404)


