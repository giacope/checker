# ---------------------------------------------------------------- version order


@pytest.mark.parametrize(
    "eco, a, b, newer",
    [
        ("npm", "4.17.21", "4.17.4", True),
        ("npm", "1.0.0", "1.0.0-rc.1", True),          # semver 11: a pre-release sorts before the release
        ("npm", "1.0.0-alpha.10", "1.0.0-alpha.2", True),
        ("npm", "1.0.0-alpha.beta", "1.0.0-alpha.1", True),
        ("npm", "1.0.0+build.5", "1.0.0", False),      # build metadata does not order
        ("Hex", "1.7.10", "1.7.9", True),
        ("PyPI", "2.0", "2.0.0", False),               # PEP 440: trailing zeros are equal
        ("PyPI", "1.0", "1.0rc1", True),
        ("PyPI", "1.0.post1", "1.0", True),
        ("PyPI", "1.0a1", "1.0.dev1", True),           # dev releases sort before pre-releases
        ("PyPI", "1!0.1", "2.0", True),                # epoch
        ("PyPI", "4.2.1", "4.2", True),
        ("RubyGems", "1.10", "1.9", True),
        ("RubyGems", "1.0.0", "1.0.0.pre", True),      # a letter makes a gem version a pre-release
        ("RubyGems", "2.2.6.2", "2.2.6", True),
    ],
)
def test_version_order(eco, a, b, newer):
    assert deps.is_newer(eco, a, b) is newer


def test_unreadable_version_is_not_ordered():
    assert deps.is_newer("PyPI", "not a version", "1.0") is None


