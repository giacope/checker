def test_cache_is_used_within_24_hours_and_refreshed_after(repo, osv, tmp_path, monkeypatch):
    cache = tmp_path / "cache"
    fake = osv(ADVISORIES)
    first = deps.analyse(repo, cache_dir=cache)
    n = len(fake.calls)
    assert (cache / "vulns" / "GHSA-p6mc-m468-83gw.json").is_file() and any((cache / "queries").iterdir())
    real_now = deps._now()
    monkeypatch.setattr(deps, "_now", lambda: real_now + 23 * 3600)
    again = deps.analyse(repo, cache_dir=cache)
    assert len(fake.calls) == n                           # nothing fetched
    assert again["elements"] == first["elements"]
    monkeypatch.setattr(deps, "_now", lambda: real_now + 25 * 3600)
    deps.analyse(repo, cache_dir=cache)
    assert len(fake.calls) > n                            # expired: asked again


