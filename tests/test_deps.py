def by_id(doc):
    return {e["id"]: e for e in doc["elements"]}


def test_analyse_end_to_end(repo, osv, tmp_path):
    fake = osv(ADVISORIES)
    doc = deps.analyse(repo, describes="shop", cache_dir=tmp_path / "cache")
    src = doc["sources"][0]
    assert src["id"] == "deps" and src["kind"] == "lockfile_osv" and src["adapter"] == "adapters.deps"
    assert src["commit"] == "0123456789abcdef0123456789abcdef01234567" and src["offline"] is False
    assert src["osv_queried_at"].endswith("Z")
    assert {l["path"] for l in src["lockfiles"]} == set(dict(deps.find_lockfiles(repo)))
    els = by_id(doc)
    lodash = els["Dependency@npm/lodash@4.17.4"]
    facts = {k: v[0]["value"] for k, v in lodash["facts"].items()}
    assert facts == {"ecosystem": "npm", "name": "lodash", "version": "4.17.4", "vulnerable": True, "fix_available": True,
                     "max_severity": "high", "advisories": "GHSA-p6mc-m468-83gw, CVE-2020-8203"}
    assert lodash["facts"]["vulnerable"][0]["at"] == "package-lock.json:" + str(line_of(NPM_V1.lstrip(), "old-lodash"))
    clean = els["Dependency@npm/lodash@4.17.21"]
    assert {k: v[0]["value"] for k, v in clean["facts"].items()} == {"ecosystem": "npm", "name": "lodash", "version": "4.17.21", "vulnerable": False}
    rack = {k: v[0]["value"] for k, v in els["Dependency@RubyGems/rack@2.2.6.2"]["facts"].items()}
    assert rack["fix_available"] is False and rack["max_severity"] == "moderate"
    assert els["Dependency@npm/mocha@10.2.0"].get("dev") is True and "dev" not in lodash
    # Element locators are lockfile#L<line>, so normir does not merge neighbouring entries as one element.
    assert els["Dependency@PyPI/pyyaml@5.1"]["at"] == "requirements.txt#L3"
    assert len(load_evidence(doc).elements) == len(doc["elements"])
    # One querybatch for all packages, one GET per advisory found.
    assert [c for c in fake.calls if c[1] == "/v1/querybatch"] == [("POST", "/v1/querybatch", len(doc["elements"]))]
    assert sorted(c[1] for c in fake.calls if c[0] == "GET") == sorted(f"/v1/vulns/{r['id']}" for r in ADVISORIES)


