def ghsa(id_, name, fixed, eco="npm", severity="HIGH", aliases=(), vectors=(), introduced="0"):
    events = [{"introduced": introduced}] + ([{"fixed": fixed}] if fixed else [])
    rec = {"id": id_, "modified": "2026-01-01T00:00:00Z", "aliases": list(aliases), "summary": f"{name} advisory {id_}",
           "affected": [{"package": {"ecosystem": eco, "name": name}, "ranges": [{"type": "SEMVER" if eco != "PyPI" else "ECOSYSTEM", "events": events}]}],
           "severity": [{"type": "CVSS_V4" if v.startswith("CVSS:4") else "CVSS_V3", "score": v} for v in vectors]}
    if severity:
        rec["database_specific"] = {"severity": severity}
    return rec


LODASH = deps.Package("npm", "lodash", "4.17.4")


def test_assess_clean_package():
    assert deps.assess(LODASH, []) == {"vulnerable": False}


def test_assess_ghsa_severity_fix_and_aliases():
    recs = [ghsa("GHSA-aaaa", "lodash", "4.17.12", severity="CRITICAL", aliases=["CVE-2019-10744"]),
            ghsa("GHSA-bbbb", "lodash", "4.17.21", severity="MODERATE", aliases=["CVE-2020-28500"])]
    assert deps.assess(LODASH, recs) == {"vulnerable": True, "fix_available": True, "max_severity": "critical",
                                         "advisories": "GHSA-aaaa, CVE-2019-10744, GHSA-bbbb, CVE-2020-28500"}


def test_assess_one_advisory_without_fix_means_no_fix_available():
    recs = [ghsa("GHSA-aaaa", "lodash", "4.17.12"), ghsa("GHSA-cccc", "lodash", None, severity="LOW")]
    assert deps.assess(LODASH, recs)["fix_available"] is False


def test_assess_fix_must_be_newer_than_the_locked_version_and_for_this_package():
    # Only a fix for an older release line, and one for another package, do not fix this version.
    old_line = ghsa("GHSA-dddd", "lodash", "3.10.2", introduced="3.0.0")
    other = ghsa("GHSA-eeee", "lodash.merge", "4.6.2")
    other["affected"].append({"package": {"ecosystem": "npm", "name": "lodash"}, "ranges": [{"type": "GIT", "events": [{"introduced": "0"}, {"fixed": "abc123"}]}]})
    assert deps.assess(LODASH, [old_line])["fix_available"] is False
    assert deps.assess(LODASH, [other])["fix_available"] is False


def test_assess_merges_records_that_alias_each_other_and_prefers_ghsa():
    p = deps.Package("PyPI", "pyyaml", "5.1")
    recs = [ghsa("PYSEC-2019-1", "PyYAML", "5.4", eco="PyPI", severity=None, aliases=["CVE-2019-20477"],
                 vectors=["CVSS:3.1/AV:N/AC:L/PR:N/UI:N/S:U/C:H/I:H/A:H"]),
            ghsa("GHSA-xxxx", "pyyaml", "5.4", eco="PyPI", severity="HIGH", aliases=["CVE-2019-20477"])]
    out = deps.assess(p, recs)
    assert out["advisories"] == "GHSA-xxxx, CVE-2019-20477"   # one advisory, not two
    assert out["max_severity"] == "high"                       # GitHub's rating wins over the PYSEC vector (9.8)
    assert out["fix_available"] is True


